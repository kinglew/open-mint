// Post-build: generate out/sw.js that precaches the whole static export so the
// app (including SQLite WASM + OCR engine) works fully offline after first load.
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { createHash } from "node:crypto";

const OUT = "out";
const files = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = "/" + relative(OUT, f).split("\\").join("/");
  if (rel === "/sw.js" || rel.endsWith(".map")) continue;
  hash.update(rel).update(readFileSync(f));
  urls.push(rel.endsWith("/index.html") ? rel.slice(0, -"index.html".length) : rel);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// generated by scripts/gen-sw.mjs
const CACHE = "mint-local-${version}";
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // Network-first for pages so updates land, cached copy offline.
    let path = url.pathname;
    if (!path.endsWith("/")) path += "/";
    e.respondWith(fetch(req).catch(() => caches.match(path).then((r) => r || caches.match("/"))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: url.pathname.startsWith("/_next/") === false }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  })));
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`sw.js: precached ${urls.length} files, cache ${version}`);
